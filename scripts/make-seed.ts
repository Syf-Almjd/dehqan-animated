// node --experimental-strip-types scripts/make-seed.ts > supabase/seed.sql
import { demoCategories, demoCoupons, demoProducts, demoReviews } from "../src/lib/data.ts";
const q = (s: string | null | undefined) => (s == null ? "null" : `'${s.replace(/'/g, "''")}'`);
let sql = "-- Demo data. Run after schema.sql (generated by scripts/make-seed.ts)\n";
demoCategories.forEach((c, i) => {
  sql += `insert into public.categories (slug,name,description,color,sort) values (${q(c.slug)},${q(c.name)},${q(c.description)},${q(c.color)},${i}) on conflict (slug) do nothing;\n`;
});
demoProducts.forEach((p) => {
  sql += `insert into public.products (slug,name,description,price_cents,compare_at_cents,category_id,art_kind,color,stock,featured) values (${q(p.slug)},${q(p.name)},${q(p.description)},${p.price_cents},${p.compare_at_cents ?? "null"},(select id from public.categories where slug=${q(p.category?.slug)}),${q(p.art_kind)},${q(p.color)},${p.stock},${p.featured}) on conflict (slug) do nothing;\n`;
});
sql += "\n-- Seeded reviews (no user attached)\ndelete from public.reviews where user_id is null;\n";
demoReviews.forEach((r) => {
  sql += `insert into public.reviews (product_id,rating,title,body,author_name,created_at) values ((select id from public.products where slug=${q(r.product_id)}),${r.rating},${q(r.title)},${q(r.body)},${q(r.author_name)},${q(r.created_at)});\n`;
});
sql += "\n";
demoCoupons.forEach((c) => {
  sql += `insert into public.coupons (code,percent_off,amount_off_cents,min_subtotal_cents) values (${q(c.code)},${c.percent_off ?? "null"},${c.amount_off_cents ?? "null"},${c.min_subtotal_cents}) on conflict (code) do nothing;\n`;
});
console.log(sql);
